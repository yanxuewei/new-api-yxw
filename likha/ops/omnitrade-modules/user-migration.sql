CREATE TABLE IF NOT EXISTS erp_user.t_department (
 id BIGINT NOT NULL PRIMARY KEY, dept_name VARCHAR(100) NOT NULL, dept_code VARCHAR(100) NOT NULL UNIQUE,
 parent_id BIGINT NOT NULL DEFAULT 0, leader VARCHAR(100),phone VARCHAR(50),email VARCHAR(200),sort INT NOT NULL DEFAULT 0,
 status TINYINT NOT NULL DEFAULT 1,create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, INDEX idx_parent(parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS erp_user.t_user_department (
 user_id BIGINT NOT NULL, department_id BIGINT NOT NULL, PRIMARY KEY(user_id,department_id), INDEX idx_dept(department_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
